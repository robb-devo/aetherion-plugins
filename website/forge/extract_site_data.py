from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'website/src/data'
OUT.mkdir(exist_ok=True)


def clean(s):
    return re.sub(r'§.', '', s or '')


def write(name, header, payload):
    body = '\n'.join(f'export const {k} = {json.dumps(v, ensure_ascii=False, indent=1)}' for k, v in payload.items())
    (OUT / name).write_text(f'// Generated by forge/extract_site_data.py from the plugin sources. {header}\n{body}\n', encoding='utf8')


