"""Pulls the website's game data out of the plugin sources, so the site quotes the game instead of paraphrasing it.
Writes src/data/*.js. Run from anywhere: python3 website/forge/extract_site_data.py

German lines come from the game's own lang files wherever they exist. Landmarks and pet notes have no
German in the game yet; those translations live here.
"""
import json
