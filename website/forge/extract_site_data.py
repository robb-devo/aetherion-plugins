pet_dir = ROOT / 'Aethermobs/src/main/java/de/aetherion/aethermobs/pet'
flavor_src = (pet_dir / 'PetFlavor.java').read_text(encoding='utf8')
cut = flavor_src.find('case "sack_of_potatoes" -> "§7" + name')
flavor = {}
for m in re.finditer(r'case ([^-]+?) -> "(§7[^"]+)"', flavor_src[:cut] if cut > 0 else flavor_src):
    for pid in re.findall(r'"([a-z_0-9]+)"', m.group(1)):
        flavor[pid] = m.group(2)[2:]
factory = (pet_dir / 'PetFactory.java').read_text(encoding='utf8')
SKIP = {'aetherion', 'hacker'}  # one is a spoiler, the other a dev joke
pets = []
for m in re.finditer(r'new PetDefinition\(\s*"([a-z_0-9]+)",\s*"([^"]+)",\s*ItemCapability\.([A-Z_]+)', factory):
    pid, name, _ = m.groups()
    if pid in SKIP or pid not in flavor:
        continue
    block = factory[m.end():m.end() + 1500]
    block = block[:block.find('return ')]
    rar = re.findall(r'Rarity\.([A-Z]+)', block)
    if pid not in DE_PETS:
        raise SystemExit(f'pet without German: {pid}')
    pets.append({'id': pid, 'name': {'en': name, 'de': DE_PETS[pid][0]}, 'note': {'en': flavor[pid], 'de': DE_PETS[pid][1]}, 'low': rar[0].lower(), 'top': rar[-1].lower()})
write('pets.js', 'Notes are the in-game Aetherlex lines; German is translated here.', {'PETS': pets})

