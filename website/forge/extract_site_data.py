def xz(s):
    x, _, z = str(s).split()
    return float(x), float(z)


districts = []
for did, d in origin['districts'].items():
    x, z = xz(d['anchor'])
    # the label sits on the middle of the first circle: the anchor is often at the rim
    cx, cz, _ = [float(v) for v in d['circles'][0].split()]
    districts.append({'id': did, 'name': d['name'], 'x': cx, 'z': cz, 'ax': x, 'az': z, 'tag': {'en': clean(d['tagline']), 'de': DE_TAG[did]}})
marks = []
for mid, m in origin['landmarks'].items():
    x, z = xz(m['anchor'] if 'anchor' in m else m.get('location') or m.get('at'))
    text = clean(m.get('desc') or m.get('tagline') or m.get('blurb') or m.get('hint'))
    marks.append({'id': mid, 'd': m['district'], 'name': m['name'], 'x': x, 'z': z, 'text': {'en': text, 'de': DE_MARK[mid]}})
